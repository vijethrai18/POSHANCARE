
const API_BASE_URL = "https://poshancare.onrender.com/api";
// HTML elements
const loginForm = document.getElementById("loginForm");
const roleSelect = document.getElementById("role");
const roleGroup = document.getElementById("roleGroup");
const childIdGroup = document.getElementById("childIdGroup");
const childIdInput = document.getElementById("childId");
const mobileInput = document.getElementById("mobile");
const otpGroup = document.getElementById("otpGroup");
const otpInput = document.getElementById("otp");
const formMessage = document.getElementById("formMessage");
const submitBtn = document.getElementById("submitBtn");
const submitText = document.getElementById("submitText");
const resendBtn = document.getElementById("resendBtn");
const loginTitle = document.getElementById("loginTitle");
const loginDescription = document.getElementById("loginDescription");

let otpRequested = false;
let requestedMobile = "";
let requestedRole = "";
let requestedChildId = "";

// Read the selected role from the homepage URL
const params = new URLSearchParams(window.location.search);
const initialRole = params.get("role");

if (initialRole === "WORKER" || initialRole === "PARENT") {
  roleSelect.value = initialRole;
  
}

// Display the correct fields for each role
function updateRoleFields() {
  const isParent = roleSelect.value === "PARENT";

  childIdGroup.hidden = !isParent;
  childIdInput.required = isParent;

  // Reset OTP state when the role changes
  otpRequested = false;
  otpGroup.hidden = true;
  otpInput.required = false;
  otpInput.value = "";
  resendBtn.hidden = true;

  submitText.textContent = "Request OTP";
  loginTitle.textContent = isParent
    ? "Parent login"
    : "Worker login";

  loginDescription.textContent = isParent
    ? "Enter your child's ID and registered mobile number."
    : "Enter your registered mobile number to continue.";

  showMessage("", "");
}

function showMessage(message, type) {
  formMessage.textContent = message;
  formMessage.className = "form-message";

  if (type) {
    formMessage.classList.add(type);
  }
}

function setLoading(isLoading, text) {
  submitBtn.disabled = isLoading;
  submitText.textContent = text;
}

// Send an OTP request to Spring Boot
async function requestOtp() {
  const role = roleSelect.value;
  const mobile = mobileInput.value.trim();
  const childId = childIdInput.value.trim();

  if (!/^[6-9]\d{9}$/.test(mobile)) {
    showMessage(
      "Enter a valid 10-digit Indian mobile number.",
      "error"
    );
    return;
  }

  if (role === "PARENT" && !childId) {
    showMessage("Please enter your Child ID.", "error");
    return;
  }

  const payload = { mobile, role };

  if (role === "PARENT") {
    payload.childId = childId;
  }

  setLoading(true, "Requesting OTP...");

  try {
    const response = await fetch(
      `${API_BASE_URL}/auth/request-otp`,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json"
        },
        body: JSON.stringify(payload)
      }
    );

  console.log("OTP request URL:", `${API_BASE_URL}/auth/request-otp`);
  console.log("OTP response status:", response.status);
  console.log("OTP response body:", await response.clone().text());

    const data = await response.json().catch(() => ({}));

    if (!response.ok) {
  throw new Error(
    `HTTP ${response.status}: ${
      data.message ||
      data.error ||
      JSON.stringify(data) ||
      "Check the Spring Boot console."
    }`
  );
}

    requestedMobile = mobile;
    requestedRole = role;
    requestedChildId = childId;
    otpRequested = true;

    otpGroup.hidden = false;
    otpInput.required = true;
    resendBtn.hidden = false;

    loginTitle.textContent = "Verify your OTP";
    loginDescription.textContent =
      "Enter the OTP generated by the development backend.";

    submitText.textContent = "Verify OTP";

    showMessage(
      data.message ||
        "OTP request accepted. Check the Spring Boot console for the development OTP.",
      "success"
    );

    otpInput.focus();
  } catch (error) {
    showMessage(
      error.message ||
        "Cannot connect to the backend. Make sure Spring Boot is running.",
      "error"
    );
  } finally {
    submitBtn.disabled = false;
  }
}

// Verify the OTP and receive the backend login token
async function verifyOtp() {
  const otp = otpInput.value.trim();

  if (!/^\d{4,8}$/.test(otp)) {
    showMessage("Enter the valid OTP shown in the backend console.", "error");
    return;
  }

  const payload = {
    mobile: requestedMobile,
    role: requestedRole,
    otp
  };

  if (requestedRole === "PARENT") {
    payload.childId = requestedChildId;
  }

  setLoading(true, "Verifying OTP...");

  try {
    const response = await fetch(
      `${API_BASE_URL}/auth/verify-otp`,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json"
        },
        body: JSON.stringify(payload)
      }
    );

    const data = await response.json().catch(() => ({}));

    if (!response.ok) {
      throw new Error(
        data.message || "OTP verification failed. Try again."
      );
    }

    if (!data.token || data.role !== requestedRole) {
      throw new Error(
        "The backend response did not contain the expected login token and role."
      );
    }

    // Save the verified session information
    const session = {
      token: data.token,
      role: data.role,
      userId: data.userId || null,
      childId: data.childId || null,
      mobile: requestedMobile
    };

    sessionStorage.setItem(
      "poshancare_session",
      JSON.stringify(session)
    );

    showMessage("Login successful! Opening your dashboard...", "success");

    // Redirect after successful verification
    window.location.href =
      requestedRole === "WORKER"
        ? "worker.html"
        : "parent.html";

  } catch (error) {
    showMessage(
      error.message ||
        "Could not verify OTP. Check the backend and try again.",
      "error"
    );
  } finally {
    submitBtn.disabled = false;
  }
}

// Form submission: first request OTP, then verify it
loginForm.addEventListener("submit", async (event) => {
  event.preventDefault();

  if (otpRequested) {
    await verifyOtp();
  } else {
    await requestOtp();
  }
});

// Request another OTP
resendBtn.addEventListener("click", async () => {
  if (!otpRequested) return;

  otpRequested = false;
  otpGroup.hidden = true;
  otpInput.required = false;
  otpInput.value = "";
  resendBtn.hidden = true;

  await requestOtp();
});

// Changing role resets the login flow
roleSelect.addEventListener("change", updateRoleFields);

// Initialize the page using the selected role
updateRoleFields();

// Restore the role passed from the homepage
if (initialRole === "WORKER" || initialRole === "PARENT") {
  roleSelect.value = initialRole;
  updateRoleFields();
}